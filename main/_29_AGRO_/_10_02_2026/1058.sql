SELECT 
D.CUIIO,
R.DENUMIRE,
D.CUATM,
D.RIND,
SUM(D.COL1) AS COL1,
SUM(D.COL2) AS COL2,
SUM(D.COL3) AS COL3,
SUM(D.COL4) AS COL4,
SUM(D.COL5) AS COL5


FROM CIS2.VW_DATA_ALL D 

                    INNER JOIN CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS 
WHERE 
D.FORM = 45 AND 
D.capitol=399 AND  D.capitol_vers=1063
AND D.PERIOADA = 1068
AND 
 D.RIND IN ('1110','1100', '1130', '1150', '1160', '1190', '1190', '1231', '1300', '1430', '1450', '1460' ,'1400') 
 
 
GROUP BY
 D.CUIIO,
D.CUATM,
R.DENUMIRE,
D.RIND