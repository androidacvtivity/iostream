
SELECT   
 CIS2.NVAL(COUNT(DISTINCT  D.CUIIO ))  AS COL1,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('1') THEN  D.CUIIO END ))  AS COL2,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('2') THEN  D.CUIIO END ))  AS COL3,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('3') THEN  D.CUIIO END ))  AS COL4,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('4') THEN  D.CUIIO END ))  AS COL5,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('5') THEN  D.CUIIO END ))  AS COL6,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('6') THEN  D.CUIIO END ))  AS COL7,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('7') THEN  D.CUIIO END ))  AS COL8
 
 
FROM   
    CIS2.VW_DATA_ALL D INNER JOIN
    (
    ------------------------------------------------------
    SELECT
 DD.CUIIO, 
 DD.CUIIO_VERS,
 SUBSTR(R.CAEM2,2,4)  AS CAEM2,
 SUM(CASE WHEN DD.ID_MD IN (69986) AND DD.COL4 IS NOT NULL THEN DD.COL4 ELSE 0 END) AS COL1,
 MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) AS CAEM_ACT,
 CASE WHEN  MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) IS NULL THEN 
 SUBSTR(R.CAEM2,2,4) ELSE  MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) END  AS CAEM_FINAL,
 SUM(CASE WHEN DD.ID_MD IN (62450) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) AS CP_SR_R4 
 FROM
   CIS2.DATA_ALL DD
                INNER JOIN CIS2.RENIM R ON R.CUIIO = DD.CUIIO AND R.CUIIO_VERS = DD.CUIIO_VERS 
 WHERE
   DD.PERIOADA IN (2014) AND
   DD.FORM=64 
  
   
   GROUP BY
   SUBSTR(R.CAEM2,2,4),
   DD.CUIIO,
   DD.CUIIO_VERS
   

   
   

   
   
    ) DD ON DD.CUIIO = D.CUIIO AND DD.CUIIO_VERS = D.CUIIO_VERS 
        
     
WHERE
  D.FORM IN (64)             AND 
 (:pID_MDTABLE=:pID_MDTABLE) AND
  D.FORM_VERS = :pFORM_VERS  AND 
  D.FORM = :pFORM  AND      
  D.PERIOADA =:pPERIOADA AND
  D.FORM IN (:pFORM) --
  AND D.CAPITOL IN (100) AND D.RIND IN ('1','2','3','4','5') 
  

