
SELECT   


 CIS2.NVAL(COUNT(DISTINCT D.CUIIO))  AS COL1,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('1') THEN  D.CUIIO END ))  AS COL2,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('2') THEN  D.CUIIO END ))  AS COL3,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('3') THEN  D.CUIIO END ))  AS COL4,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('4') THEN  D.CUIIO END ))  AS COL5,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('5') THEN  D.CUIIO END ))  AS COL6,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('6') THEN  D.CUIIO END ))  AS COL7,
 CIS2.NVAL(COUNT(DISTINCT CASE WHEN D.CAPITOL IN (100)   AND D.RIND IN ('7') THEN  D.CUIIO END ))  AS COL8
 
 
FROM   
    CIS2.VW_DATA_ALL D
     
        
     
WHERE
  D.FORM IN (64)             AND 
 (:pID_MDTABLE=:pID_MDTABLE) AND
  D.FORM_VERS = :pFORM_VERS  AND 
  D.FORM = :pFORM  AND      
  D.PERIOADA =:pPERIOADA 

  

 