SELECT
CC.CODUL,
CC.DENUMIRE,
CC.FULL_CODE,
COUNT(DISTINCT D.CUIIO) AS COL1,
SUM(CASE WHEN D.capitol=1125 AND  D.RIND IN ('300') THEN  D.COL1 END) AS COL2,
SUM(CASE WHEN D.capitol=1125 AND  D.RIND IN ('310') THEN  D.COL1 END) AS COL3,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('320') THEN  D.COL1 END) AS COL4,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('320') THEN  D.COL2 END) AS COL5,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('330') THEN  D.COL1 END) AS COL6,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('330') THEN  D.COL2 END) AS COL7,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('340') THEN  D.COL1 END) AS COL8,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('340') THEN  D.COL2 END) AS COL9,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('350') THEN  D.COL1 END) AS COL10,
SUM(CASE WHEN D.capitol=1126 AND  D.RIND IN ('350') THEN  D.COL2 END) AS COL11,
SUM(CASE WHEN D.capitol=1127 AND  D.RIND IN ('400') THEN  D.COL3 END) AS COL12,
SUM(CASE WHEN D.capitol=1127 AND  D.RIND IN ('400') THEN  D.COL4 END) AS COL13,
SUM(CASE WHEN D.capitol=1127 AND  D.RIND IN ('400') THEN  D.COL5 END) AS COL14,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('500') THEN  D.COL8 END) AS COL15,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('500') THEN  D.COL9 END) AS COL16,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('500') THEN  D.COL10 END) AS COL17,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('510') THEN  D.COL8 END) AS COL18,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('510') THEN  D.COL9 END) AS COL19,
SUM(CASE WHEN D.capitol=1128 AND  D.RIND IN ('510') THEN  D.COL10 END) AS COL20,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('900') THEN  D.COL10 END) AS COL21,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('910') THEN  D.COL10 END) AS COL22,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('920') THEN  D.COL10 END) AS COL23,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('930') THEN  D.COL10 END) AS COL24,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('940') THEN  D.COL10 END) AS COL25,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('950') THEN  D.COL10 END) AS COL26,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('960') THEN  D.COL10 END) AS COL27,
SUM(CASE WHEN D.capitol=2014 AND  D.RIND IN ('970') THEN  D.COL10 END) AS COL28



FROM   
        
    CIS2.VW_DATA_ALL D INNER JOIN 
    (
    ------------------------------------------------------
    SELECT
 DD.CUIIO, 
 DD.CUIIO_VERS,
 SUBSTR(R.CAEM2,2,4)  AS CAEM2,
 SUM(CASE WHEN DD.ID_MD IN (69986) AND DD.COL4 IS NOT NULL THEN DD.COL4 ELSE 0 END) AS COL1,
 MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) AS CAEM_ACT,
 CASE WHEN  MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) IS NULL THEN 
 SUBSTR(R.CAEM2,2,4) ELSE  MAX(CASE WHEN DD.ID_MD = 61832 THEN DD.COL31 END) END  AS CAEM_FINAL,
 SUM(CASE WHEN DD.ID_MD IN (62450) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) AS CP_SR_R4 
 FROM
   CIS2.DATA_ALL DD
                INNER JOIN CIS2.RENIM R ON R.CUIIO = DD.CUIIO AND R.CUIIO_VERS = DD.CUIIO_VERS 
 WHERE
   DD.PERIOADA IN (2014) AND
   DD.FORM=64 AND
   DD.ID_MD IN (69986,61832,62450,62382,114173,114171) --64_100_62450_4_1
   
   GROUP BY
   SUBSTR(R.CAEM2,2,4),
   DD.CUIIO,
   DD.CUIIO_VERS
   

   
   HAVING
   (NVAL(SUM(CASE WHEN DD.ID_MD IN (69986) AND DD.COL4 IS NOT NULL THEN DD.COL4 ELSE 0 END)) >= 0
   AND 
   NVAL(SUM(CASE WHEN DD.ID_MD IN (69986) AND DD.COL4 IS NOT NULL THEN DD.COL4 ELSE 0 END)) <=249)
   
   AND 
   
   SUM(CASE WHEN DD.ID_MD IN (62450) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) <> 1
   
   AND 
   (
   SUM(CASE WHEN DD.ID_MD IN (62382) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) =  1 -- 64_100_62382_1_1
   OR 
   SUM(CASE WHEN DD.ID_MD IN (114173,114171) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) >  0  --64_100_114173_6_164_100_114171_5_1   )
      )

   
   
    ) DD ON DD.CUIIO = D.CUIIO AND DD.CUIIO_VERS = D.CUIIO_VERS 
    
    INNER JOIN (
    SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                
(
                CODUL LIKE 'C%'
                OR CODUL LIKE 'B%'
                OR CODUL LIKE 'D%'
                OR CODUL LIKE 'E%'
                OR CODUL LIKE 'F%'
                OR CODUL LIKE 'G%'
                OR CODUL LIKE 'H%'
                OR CODUL LIKE 'I%'
                OR CODUL LIKE 'K%'
                OR CODUL LIKE 'J%'
                OR CODUL LIKE 'L%'
                OR CODUL LIKE 'M%'
                OR CODUL LIKE 'Q%'
                OR CODUL LIKE 'P%'
                OR CODUL LIKE 'N%'
                OR CODUL LIKE 'R%'
                OR CODUL LIKE 'S%'
                )
                
                AND 
                
                SUBSTR(CODUL,1,3) NOT IN ('S94','K65')
                AND 
                CODUL NOT IN ('K6419','K6411')
                
                
                
    ) C ON SUBSTR(C.CODUL,2,4)  = DD.CAEM_FINAL
    INNER JOIN CIS2.VW_CL_CAEM2 CC ON (C.FULL_CODE LIKE '%'||CC.CODUL||';%')
    
                
    
   WHERE
  (D.FORM=:pFORM) AND
  (D.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
   --(D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
     D.PERIOADA IN (:pPERIOADA) 
    AND D.capitol IN (1124,1125,1214,1128,1127,1126)
   

   AND  D.CUIIO=40209448
   
   GROUP BY 
   CC.CODUL,
   CC.DENUMIRE,
   CC.FULL_CODE
 
   
   ORDER BY
   CC.FULL_CODE