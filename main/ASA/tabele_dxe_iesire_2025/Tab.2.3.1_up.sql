                OR CODUL LIKE 'L%'
                OR CODUL LIKE 'M%'
                OR CODUL LIKE 'Q%'
                OR CODUL LIKE 'P%'
                OR CODUL LIKE 'N%'
                OR CODUL LIKE 'R%'
                OR CODUL LIKE 'S%'
                )
                
                AND 
                
                SUBSTR(CODUL,1,3) NOT IN ('S94','K65')
                AND 
                CODUL NOT IN ('K6419','K6411')
                
                
                
    ) C ON SUBSTR(C.CODUL,2,4)  = DD.CAEM_FINAL
    INNER JOIN CIS2.VW_CL_CAEM2 CC ON (C.FULL_CODE LIKE '%'||CC.CODUL||';%')
    
                
    
   WHERE
  (D.FORM=:pFORM) AND
  (D.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
   --(D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
     D.PERIOADA IN (:pPERIOADA) 
   -- AND D.capitol IN (1124,1125)
   
   AND CC.CODUL IN (
'00000',
'B0000',
'C0000',
'D0000',
'E0000',
'F0000',
'G0000',
'H0000',
'I0000',
'J0000',
'K0000',
'L0000',
'M0000',
'N0000',
'P0000',
'Q0000',
'R0000',
'S0000'

   )
 --  AND  D.CUIIO=40209448
   
   GROUP BY 
   CC.CODUL,
   CC.DENUMIRE,
   CC.FULL_CODE
 
   
   ORDER BY
   CC.FULL_CODE