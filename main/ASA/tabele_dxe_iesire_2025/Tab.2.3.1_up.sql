   SUM(CASE WHEN DD.ID_MD IN (62450) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) <> 1
   
   AND 
   (
   SUM(CASE WHEN DD.ID_MD IN (62382) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) =  1 -- 64_100_62382_1_1
   OR 
   SUM(CASE WHEN DD.ID_MD IN (114171) AND DD.COL1 IS NOT NULL THEN DD.COL1 ELSE 0 END) >  0  --64_100_114173_6_164_100_114171_5_1   )
      )

   
   
    ) DD ON DD.CUIIO = D.CUIIO AND DD.CUIIO_VERS = D.CUIIO_VERS 
    
    INNER JOIN (
    SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                
       (
                CODUL LIKE 'C%'
                OR CODUL LIKE 'B%'
                OR CODUL LIKE 'D%'
                OR CODUL LIKE 'E%'
                OR CODUL LIKE 'F%'
