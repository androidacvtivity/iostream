    (
    ------------------------------------------------------
    SELECT
 DD.CUIIO, 
 DD.CUIIO_VERS,
 SUBSTR(R.CAEM2,2,4)  AS CAEM2,
 SUM(CASE WHEN DD.ID_MD IN (69986) AND DD.COL4 IS NOT NULL THEN DD.COL4 ELSE 0 END) AS COL1,
