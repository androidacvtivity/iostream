SELECT
  D.CUIIO,
  D.CAEM2,
 
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('498') THEN D.COL2 ELSE  NULL END ) AS RIND_498_C2,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('498') THEN D.COL3 ELSE  NULL END ) AS RIND_498_C3,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('498') THEN D.COL4 ELSE  NULL END ) AS RIND_498_C4,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('498') THEN D.COL5 ELSE  NULL END ) AS RIND_498_C5,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('498') THEN D.COL6 ELSE  NULL END ) AS RIND_498_C6,
  
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL1 ELSE  NULL END ) AS RIND_999_C1,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL2 ELSE  NULL END ) AS RIND_999_C2,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL3 ELSE  NULL END ) AS RIND_999_C3,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL4 ELSE  NULL END ) AS RIND_999_C4,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL5 ELSE  NULL END ) AS RIND_999_C5,
  SUM(CASE WHEN  D.CAPITOL IN (1017) AND D.RIND IN ('999') THEN D.COL6 ELSE  NULL END ) AS RIND_999_C6,
  
  SUM(CASE WHEN  D.CAPITOL IN (1018) AND D.RIND IN ('2001') THEN D.COL1 ELSE  NULL END ) AS RIND_2001_C1,
  SUM(CASE WHEN  D.CAPITOL IN (1018) AND D.RIND IN ('2001') THEN D.COL2 ELSE  NULL END ) AS RIND_2001_C2,
  SUM(CASE WHEN  D.CAPITOL IN (1018) AND D.RIND IN ('2001') THEN D.COL3 ELSE  NULL END ) AS RIND_2001_C3
  
  


  
FROM
  CIS2.VW_DATA_ALL D
          
          
  
WHERE
  (D.PERIOADA =:pPERIOADA) AND 
  (D.FORM =:pFORM) AND
  (D.FORM_VERS =:pFORM_VERS) AND 
  (:pID_MDTABLE =:pID_MDTABLE) AND
  
   D.FORM IN (19)
   AND D.CAEM2 LIKE 'I55%'

    
GROUP BY
  D.CUIIO,
  D.CAEM2
  
  ORDER BY 
  D.CUIIO,
  D.CAEM2