CREATE OR REPLACE FORCE VIEW USER_BANCU.VW_RSF1_2014
AS

SELECT 
        
            D.CUIIO,
            SUM(CASE WHEN D.ID_MD = 62198 THEN D.COL2 ELSE NULL END)  A2_020_C2,
            SUM(CASE WHEN D.ID_MD = 62208 THEN D.COL2 ELSE NULL END)  A2_050_C2,
            SUM(CASE WHEN D.ID_MD = 62209 THEN D.COL2 ELSE NULL END)  A2_060_C2,
            SUM(CASE WHEN D.ID_MD = 62200 THEN D.COL2 ELSE NULL END)  A2_070_C2,
            NVAL(SUM(CASE WHEN D.ID_MD = 62198 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 62208 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 62209 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 62200 THEN D.COL2 ELSE NULL END)) SUM_020_050_060_070,
            SUM(CASE WHEN D.ID_MD = 62203 THEN D.COL2 ELSE NULL END)  A2_080_C2
             
            
            FROM CIS2.DATA_ALL_FR D
            
              WHERE 
              D.PERIOADA = 2014 
              AND D.FORM = 57
              AND D.FORM_VERS = 2009
            --   AND D.CUIIO = 2561932
              GROUP BY 
              D.CUIIO