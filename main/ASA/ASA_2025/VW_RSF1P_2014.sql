CREATE OR REPLACE FORCE VIEW USER_BANCU.VW_RSF1P_2014
AS

SELECT 
        
            D.CUIIO,
            SUM(CASE WHEN D.ID_MD = 61890 THEN D.COL2 ELSE NULL END)  R1P_A2_020_C2,
            SUM(CASE WHEN D.ID_MD = 61871 THEN D.COL2 ELSE NULL END)  R1P_A2_050_C2,
            SUM(CASE WHEN D.ID_MD = 61872 THEN D.COL2 ELSE NULL END)  R1P_A2_060_C2,
            SUM(CASE WHEN D.ID_MD = 61873 THEN D.COL2 ELSE NULL END)  R1P_A2_070_C2,
            NVAL(SUM(CASE WHEN D.ID_MD = 61890 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 61871 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 61872 THEN D.COL2 ELSE NULL END)) +
            NVAL(SUM(CASE WHEN D.ID_MD = 61873 THEN D.COL2 ELSE NULL END)) R1P__SUM_020_050_060_070,
            SUM(CASE WHEN D.ID_MD = 61874 THEN D.COL2 ELSE NULL END)  R1P_A2_080_C2
             
            
            FROM CIS2.DATA_ALL_FR D
            
              WHERE 
              D.PERIOADA = 2014 
              AND D.FORM = 63
              AND D.FORM_VERS = 2000
            --   AND D.CUIIO = 2561932
              GROUP BY 
              D.CUIIO