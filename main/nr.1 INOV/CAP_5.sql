
SELECT
    D.ANUL,
    D.CUIIO,
    R.DENUMIRE,
    R.CUATM,
    R.CAEM2,
   SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND IN ('2.1.1')  THEN D.COL1 ELSE 0 END) AS R_2_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND IN ('2.1.1')  THEN D.COL2 ELSE 0 END) AS R_2_1_1_C2,
   
   SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND IN ('2.1.2')  THEN D.COL1 ELSE 0 END) AS R_2_1_2_C1,
   SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND IN ('2.1.2')  THEN D.COL2 ELSE 0 END) AS R_2_1_2_C2,
   
   SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND IN ('3.1.1')  THEN D.COL1 ELSE 0 END) AS R_3_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND IN ('3.1.2')  THEN D.COL1 ELSE 0 END) AS R_3_1_2_C1,
   SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND IN ('3.1.3')  THEN D.COL1 ELSE 0 END) AS R_3_1_3_C1,
   
   SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND IN ('4.1.1')  THEN D.COL1 ELSE 0 END) AS R_4_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND IN ('4.1.2')  THEN D.COL1 ELSE 0 END) AS R_4_1_2_C1,
   
   SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND IN ('5.1.1')  THEN D.COL1 ELSE 0 END) AS R_5_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND IN ('5.14')  THEN D.COL1 ELSE 0 END) AS R_5_1_4_C1,
   
   SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND IN ('7.1.1')  THEN D.COL1 ELSE 0 END) AS R_7_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND IN ('7.1.2')  THEN D.COL1 ELSE 0 END) AS R_7_1_2_C1,
   SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND IN ('7.1.3')  THEN D.COL1 ELSE 0 END) AS R_7_1_3_C1,
   
   SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND IN ('8.1.1')  THEN D.COL1 ELSE 0 END) AS R_8_1_1_C1,
   SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND IN ('8.1.2')  THEN D.COL1 ELSE 0 END) AS R_8_1_2_C1,
   SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND IN ('8.1.3')  THEN D.COL1 ELSE 0 END) AS R_8_1_3_C1,
   SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND IN ('8.1.3')  THEN D.COL1 ELSE 0 END) AS R_8_1_4_C1
   
    
  FROM CIS2.VW_DATA_ALL D inner join CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS 
                        
  WHERE PERIOADA = :pPERIOADA
    AND FORM     = :pFORM
   
  
    
  GROUP BY 
    D.CUIIO,
    R.CUATM,
    R.DENUMIRE,
    R.CAEM2,
    D.ANUL
    
    ORDER BY 
    R.CUATM