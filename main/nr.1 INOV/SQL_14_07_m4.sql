SELECT
    D.ANUL,
    D.CUIIO,
    R.DENUMIRE,
    R.CUATM,
    R.CAEM2,
    SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND = '2.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_2_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND = '2.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_2_1_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_3_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_3_1_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.3'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_3_1_3_C1,
    
    SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND = '4.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_4_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND = '4.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_4_1_2_C1,
    
    SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_5_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_5_1_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.3'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_5_1_3_C1,
    SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.4'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_5_1_4_C1,
    
    
    SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_7_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_7_1_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.3'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_7_1_3_C1,
    
    
    SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_8_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_8_1_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.3'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_8_1_3_C1,
    SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.4'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_8_1_4_C1
    
    

FROM CIS2.VW_DATA_ALL D
INNER JOIN CIS2.RENIM R 
    ON R.CUIIO = D.CUIIO 
   AND R.CUIIO_VERS = D.CUIIO_VERS
   
   
   
   WHERE PERIOADA = :pPERIOADA
    AND FORM     = :pFORM
    
    
    group by
     D.ANUL,
    D.CUIIO,
    R.DENUMIRE,
    R.CUATM,
    R.CAEM2
    
    HAVING
    (
        SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND = '2.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1041 AND D.RIND = '2.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1042 AND D.RIND = '3.1.3'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
    )

    AND

    (
        SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND = '4.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
        OR
        SUM(CASE WHEN D.CAPITOL = 1043 AND D.RIND = '4.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
        OR
        SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
        OR
        SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
        OR
        SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.3'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
        OR
        SUM(CASE WHEN D.CAPITOL = 1044 AND D.RIND = '5.1.4'
                 THEN NVL(D.COL1, 0) ELSE 0 END) > 0
    )

    AND

    (
        SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1046 AND D.RIND = '7.1.3'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.1'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.2'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.3'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
        AND
        SUM(CASE WHEN D.CAPITOL = 1047 AND D.RIND = '8.1.4'
                 THEN NVL(D.COL1, 0) ELSE 0 END) IN (0, 2)
    )

ORDER BY R.CUATM;
    

