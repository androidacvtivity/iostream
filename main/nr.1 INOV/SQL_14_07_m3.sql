SELECT
    D.ANUL,
    D.CUIIO,
    R.DENUMIRE,
    R.CUATM,
    R.CAEM2,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_1_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_1_2_C1,
    
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.2'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_2_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.3'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_3_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.4'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_4_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.5'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_5_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.6'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_6_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.7'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_5_7_C1,
    
    
    
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.1'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_7_1_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.4'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_7_4_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.5'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_7_5_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.6'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_7_6_C1,
    SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.7'  THEN NVL(D.COL1, 0) ELSE 0 END) AS R_1_7_7_C1
    
    
    
    
    
    
    

FROM CIS2.VW_DATA_ALL D
INNER JOIN CIS2.RENIM R 
    ON R.CUIIO = D.CUIIO 
   AND R.CUIIO_VERS = D.CUIIO_VERS
   
   
   
   WHERE PERIOADA = :pPERIOADA
    AND FORM     = :pFORM
    
    
    group by
     D.ANUL,
    D.CUIIO,
    R.DENUMIRE,
    R.CUATM,
    R.CAEM2
    
    
    HAVING
    
     (SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.1.1'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.1.2'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.1'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.2'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.3'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.4'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.5'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.6'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 AND 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.5.7'  THEN NVL(D.COL1, 0) ELSE 0 END) = 0 )
     
     AND 
     
     (SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.1'  THEN NVL(D.COL1, 0) ELSE 0 END) = 1 OR 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.4'  THEN NVL(D.COL1, 0) ELSE 0 END) = 1 OR 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.5'  THEN NVL(D.COL1, 0) ELSE 0 END) = 1 OR 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.6'  THEN NVL(D.COL1, 0) ELSE 0 END) = 1 OR 
     SUM(CASE WHEN D.CAPITOL = 1040 AND D.RIND = '1.7.7'  THEN NVL(D.COL1, 0) ELSE 0 END) = 1 )